import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('unsmoothed survey imports, calculates and compares construction while split-water failure preserves history', async ({ page, request }) => {
  const project=await (await request.get('/api/sample')).json();
  project.id=`irregular-${crypto.randomUUID()}`;project.name='E2E 起伏保持の合成横断';
  project.river.discharge=15;project.river.boundary.depth=3.6;project.scenarios=[];
  expect((await request.post('/api/projects',{data:project})).ok()).toBeTruthy();
  await page.goto('/');
  await page.getByLabel('保存済みプロジェクト').selectOption({label:project.name});
  await page.getByRole('button',{name:'横断面エディタ',exact:true}).click();
  const points=[[-10,6],[-5,.6],[-3,0],[-1,.12],[1,.04],[3,.18],[5,.5],[9,6]];
  let csv='station,chainage_m,bed_elevation_m,roughness,x_m,elevation_m\n';
  for(let i=0;i<11;i++)for(const [x,z] of points)csv+=`S${i},${i*40},${20-i*.04},.035,${x},${z}\n`;
  await page.getByLabel('横断測量CSV',{exact:true}).setInputFiles({name:'irregular-synthetic.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
  await page.getByLabel('CSVの高さの解釈').selectOption('relative');
  await page.getByLabel('取込みデータの標高系').fill('合成基準高');
  await page.getByRole('button',{name:'CSVを検証・プレビュー'}).click();
  await expect(page.getByText('取込みプレビュー: 11 断面。確認前の条件は変更されていません。')).toBeVisible();
  await expect(page.locator('.import-preview')).toContainText('起伏のある地盤点を保持');
  const importedResponse=page.waitForResponse(r=>r.url().endsWith('/api/imports/survey/apply'));
  await page.getByRole('button',{name:'内容を確認して全測点を置換・施工案をクリア'}).click();
  const imported=await (await importedResponse).json();
  imported.river.stations.forEach((s:{section:{points:{x:number;z:number}[]}})=>expect(s.section.points).toEqual(points.map(([x,z])=>({x,z}))));
  await page.getByRole('button',{name:'水理計算',exact:true}).click();
  const savedResponse=page.waitForResponse(r=>r.url().endsWith('/api/runs')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'計算を実行',exact:true}).click();
  const saved=await (await savedResponse).json();
  await expect(page.getByText('数値計算と施工比較が完了しました')).toBeVisible();
  expect(saved.analysis.run.engine_version).toBe('0.2.0');
  expect(saved.analysis.run.river.stations).toEqual(imported.river.stations);
  for(const row of saved.analysis.run.profile.rows) {expect(row.depth).toBeGreaterThan(.12);expect(row.froude).toBeLessThan(.98);}
  await page.getByRole('button',{name:'施工シナリオ比較',exact:true}).click();
  await page.getByRole('button',{name:'案を追加'}).click();
  const compareResponse=page.waitForResponse(r=>r.url().endsWith('/api/runs')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'計算を実行',exact:true}).click();
  const comparison=await (await compareResponse).json();
  expect(comparison.analysis.comparisons).toHaveLength(1);
  expect(comparison.analysis.comparisons[0].max_water_change).toBeLessThan(0);
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'レポート',exact:true}).click();
  const html=await readFile((await (await download).path())!,'utf8');
  expect(html).toContain('起伏を保持');expect(html).toContain(comparison.analysis.run.executed_at);
  await page.getByRole('button',{name:'水理計算',exact:true}).click();
  await page.getByLabel('境界条件 / 流況').selectOption('supercritical');
  await page.getByLabel('境界水深 (m / 河床から)').fill('.08');
  await page.getByRole('button',{name:'計算を実行',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('分離した流路');
  const history=await (await request.get(`/api/projects/${project.id}/runs`)).json();
  expect(history.items).toHaveLength(2);
  expect(await (await request.get(`/api/runs/${saved.id}`)).json()).toEqual(saved);
});
