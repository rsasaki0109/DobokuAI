import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

test('horizontal metres and survey-foot heights require explicit choices and persist as SI', async ({ page, request }) => {
  const project = await (await request.get('/api/sample')).json();
  project.id = `mixed-survey-${crypto.randomUUID()}`;
  project.name = project.id;
  expect((await request.post('/api/projects', { data: project })).ok()).toBeTruthy();
  const csv = await readFile('../../examples/synthetic-mixed-units.csv', 'utf8');
  await page.goto('/');
  await page.getByLabel('保存済みプロジェクト').selectOption(project.id);
  await page.getByRole('button', { name: '横断面エディタ', exact: true }).click();
  await page.getByLabel('横断測量CSV', { exact: true }).setInputFiles({ name: 'synthetic-mixed-units.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) });
  await page.getByLabel('取込みデータの標高系').fill('合成の共通基準高・混合単位照査');
  await page.getByRole('checkbox', { name: '高さの単位を別に指定' }).check();
  await expect(page.getByLabel('CSVの距離の単位', { exact: true })).toHaveValue('m');
  await page.getByLabel('CSVの高さの単位', { exact: true }).selectOption('us_survey_ft');
  const inspect = async () => {
    const response = page.waitForResponse(r => r.url().endsWith('/api/imports/survey/preview'));
    await page.getByRole('button', { name: 'CSVを検証・プレビュー', exact: true }).click();
    return (await response).json();
  };
  const preview = await inspect();
  expect(preview.valid).toBe(true);
  expect(preview.stations[1].chainage).toBe(1200);
  expect(preview.stations[0].bed_elevation).toBeCloseTo(1200, 10);
  expect(preview.stations[0].section.points[0].x).toBe(-22);
  expect(preview.stations[0].section.points[0].z).toBeCloseTo(9, 10);
  expect(preview.reference.import.unit).toBe('m');
  expect(preview.reference.import.vertical_unit).toBe('us_survey_ft');
  expect(await (await request.get(`/api/projects/${project.id}`)).json()).toEqual(project);
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: '取込み点検JSONを保存', exact: true }).click();
  const inspection = JSON.parse(await readFile((await (await downloaded).path())!, 'utf8'));
  expect(inspection.source.csv).toBe(csv);
  expect(inspection.source.unit).toBe('m');
  expect(inspection.source.vertical_unit).toBe('us_survey_ft');
  expect(inspection.preview).toEqual(preview);
  const confirm = page.getByRole('button', { name: '内容を確認して全測点を置換・施工案をクリア' });
  await page.getByLabel('CSVの高さの単位', { exact: true }).selectOption('ft');
  await expect(confirm).toHaveCount(0);
  expect((await inspect()).valid).toBe(false);
  await page.getByRole('checkbox', { name: '高さの単位を別に指定' }).uncheck();
  await expect(page.getByLabel('CSVの高さの単位', { exact: true })).toHaveCount(0);
  expect((await inspect()).valid).toBe(false);
  expect(await (await request.get(`/api/projects/${project.id}`)).json()).toEqual(project);
  await page.getByRole('checkbox', { name: '高さの単位を別に指定' }).check();
  await page.getByLabel('CSVの高さの単位', { exact: true }).selectOption('us_survey_ft');
  expect((await inspect()).valid).toBe(true);
  await confirm.click();
  await page.getByRole('button', { name: 'プロジェクトを保存', exact: true }).click();
  const saved = await (await request.get(`/api/projects/${project.id}`)).json();
  expect(saved.reference.import.unit).toBe('m');
  expect(saved.reference.import.vertical_unit).toBe('us_survey_ft');
  expect(saved.reference.import.sha256).toBe(createHash('sha256').update(csv).digest('hex'));
  expect(saved.river.stations[0].section.points[0].x).toBe(-22);
  expect(saved.river.discharge).toBe(project.river.discharge);
  expect(saved.river.boundary).toEqual(project.river.boundary);
  const calculated = page.waitForResponse(r => r.url().endsWith('/api/runs') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '計算を実行', exact: true }).click();
  const run = await (await calculated).json();
  expect(run.analysis.project.reference.import).toEqual(saved.reference.import);
  expect(run.analysis.run.profile.rows[1].chainage).toBe(1200);
  await expect(page.getByText('数値計算と施工比較が完了しました')).toBeVisible();
  await page.reload();
  await page.getByLabel('保存済みプロジェクト').selectOption(project.id);
  await page.getByRole('button', { name: '横断面エディタ', exact: true }).click();
  await expect(page.getByText('元CSVの距離: m / 高さ: us_survey_ft。保存済みの断面はmです。')).toBeVisible();
  expect(await (await request.get(`/api/runs/${run.id}`)).json()).toEqual(run);
  const html = await (await request.get(`/api/runs/${run.id}/reports/html`)).text();
  expect(html).toContain('距離 m / 高さ us_survey_ft');
  await page.screenshot({ path: '../../.local/mixed-survey-import-20261012.png', fullPage: true });
});
