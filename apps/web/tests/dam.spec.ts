import { test, expect } from '@playwright/test';

test('dam conditions require confirmation, compare and restore server snapshots without river edits', async ({ page, request }) => {
  const project = await (await request.get('/api/projects/sample-river')).json();
  await page.goto('/?view=dam');
  await expect(page.getByRole('heading', { name: 'ダム予備照査', exact: true })).toBeVisible();
  const calculate = page.getByRole('button', { name: '条件を確認して計算', exact: true });
  await expect(calculate).toBeDisabled();
  await page.getByLabel('条件と適用範囲を確認しました').check();
  const originalResponse = page.waitForResponse(r => r.url().endsWith('/api/dams/runs') && r.request().method() === 'POST');
  await calculate.click();
  const original = await (await originalResponse).json();
  await expect(page.getByTestId('dam-discharge')).toHaveText('96.17');
  await expect(page.getByText('全幅接触', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '基準に固定', exact: true }).click();
  await page.getByLabel('上流水深 (m)', { exact: true }).fill('26');
  await expect(calculate).toBeDisabled();
  await expect(page.getByTestId('dam-discharge')).toHaveCount(0);
  await page.getByLabel('条件と適用範囲を確認しました').check();
  await calculate.click();
  await expect(page.getByTestId('dam-discharge')).toHaveText('34.00');
  await expect(page.getByRole('columnheader', { name: '差・現在−基準' })).toBeVisible();
  await expect(page.getByRole('cell', { name: '-62.167', exact: true })).toBeVisible();
  const csvDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'CSVを保存', exact: true }).click();
  expect((await csvDownload).suggestedFilename()).toMatch(/doboku-dam-\d+\.csv/);
  const htmlDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'HTMLを保存', exact: true }).click();
  expect((await htmlDownload).suggestedFilename()).toMatch(/doboku-dam-\d+\.html/);
  let postCount = 0;
  page.on('request', r => { if (r.method() === 'POST' && r.url().includes('/api/dams/')) postCount++; });
  await page.getByRole('button', { name: `#${original.id} · ${original.run.conditions.name}`, exact: false }).click();
  await expect(page.getByTestId('dam-discharge')).toHaveText('96.17');
  await expect(page.getByLabel('上流水深 (m)', { exact: true })).toHaveValue('27');
  expect(postCount).toBe(0);
  expect(await (await request.get(`/api/dams/runs/${original.id}`)).json()).toEqual(original);
  expect(await (await request.get('/api/projects/sample-river')).json()).toEqual(project);
  await page.reload();
  await expect(page.getByRole('button', { name: `#${original.id} · ${original.run.conditions.name}`, exact: false })).toBeVisible();
});

test('invalid dam and submerged overflow are rejected; partial contact has no fabricated pressure', async ({ page, request }) => {
  await page.goto('/?view=dam');
  await expect(page.getByLabel('上流水深 (m)', { exact: true })).toHaveValue('27');
  const before = await (await request.get('/api/dams/runs')).json();
  const calculate = page.getByRole('button', { name: '条件を確認して計算', exact: true });
  await page.getByLabel('上流水深 (m)', { exact: true }).fill('31');
  await page.getByLabel('条件と適用範囲を確認しました').check();
  await calculate.click();
  await expect(page.getByRole('alert')).toContainText('上流水深');
  await expect(page.getByTestId('dam-discharge')).toHaveCount(0);
  expect(await (await request.get('/api/dams/runs')).json()).toEqual(before);
  await page.getByLabel('上流水深 (m)', { exact: true }).fill('27');
  await page.getByLabel('下流水深 (m)', { exact: true }).fill('25');
  await page.getByLabel('条件と適用範囲を確認しました').check();
  await calculate.click();
  await expect(page.getByRole('alert')).toContainText('潜り越流');
  expect(await (await request.get('/api/dams/runs')).json()).toEqual(before);
  await page.getByLabel('下流水深 (m)', { exact: true }).fill('3');
  await page.getByLabel('底幅 (m)', { exact: true }).fill('15');
  await page.getByLabel('条件と適用範囲を確認しました').check();
  const savedResponse = page.waitForResponse(r => r.url().endsWith('/api/dams/runs') && r.request().method() === 'POST');
  await calculate.click();
  const saved = await (await savedResponse).json();
  expect(saved.run.statics.contact).toBe('partial');
  expect(saved.run.statics.heel_pressure_kpa).toBeNull();
  expect(saved.run.statics.toe_pressure_kpa).toBeNull();
  await expect(page.getByText('部分接触 · 接触圧は未計算', { exact: true })).toBeVisible();
  await expect(page.getByRole('img', { name: '基礎の接触圧分布', exact: true })).toHaveCount(0);
  const report = await (await request.get(`/api/dams/runs/${saved.id}/reports/html`)).text();
  expect(report).toContain('部分接触');
  expect(report).toContain(saved.run.executed_at);
});
