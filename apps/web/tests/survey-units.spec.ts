import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

test('explicit survey feet preview converts to SI, rejects conflicting headers and retains original source in saved results', async ({ page, request }) => {
  const project = await (await request.get('/api/sample')).json();
  project.id = `survey-units-${crypto.randomUUID()}`;
  project.name = project.id;
  expect((await request.post('/api/projects', { data: project })).ok()).toBeTruthy();
  let csv = 'station,chainage_us_survey_ft,bed_elevation_us_survey_ft,roughness,x_us_survey_ft,elevation_us_survey_ft\n';
  for (const [id, chainage, bed] of [['U',0,3937],['D',3937,3936]] as const) {
    for (const [x,z] of [[-7874,29.5275],[-3937,0],[3937,0],[7874,29.5275]]) csv += `${id},${chainage},${bed},.03,${x},${z}\n`;
  }
  await page.goto('/');
  await page.getByLabel('保存済みプロジェクト').selectOption(project.id);
  await page.getByRole('button', { name:'横断面エディタ',exact:true }).click();
  await page.getByLabel('横断測量CSV', { exact:true }).setInputFiles({ name:'synthetic-us-foot.csv',mimeType:'text/csv',buffer:Buffer.from(csv) });
  await page.getByLabel('CSVの距離・高さの単位').selectOption('us_survey_ft');
  await page.getByLabel('CSVの高さの解釈').selectOption('relative');
  await page.getByLabel('取込みデータの標高系').fill('合成基準高・単位照査');
  await page.getByText('出典・利用条件を記録',{exact:true}).click();
  await page.getByLabel('データ種別',{exact:true}).selectOption('synthetic');
  const pending = page.waitForResponse(r => r.url().endsWith('/api/imports/survey/preview'));
  await page.getByRole('button', { name:'CSVを検証・プレビュー',exact:true }).click();
  const preview = await (await pending).json();
  expect(preview.valid).toBeTruthy();
  expect(preview.stations[1].chainage).toBeCloseTo(1200,10);
  expect(preview.stations[0].section.points[0].z).toBeCloseTo(9,10);
  await expect(page.getByText('取込みプレビュー: 2 断面。確認前の条件は変更されていません。')).toBeVisible();
  expect(await (await request.get(`/api/projects/${project.id}`)).json()).toEqual(project);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name:'取込み点検JSONを保存' }).click();
  const evidence = JSON.parse(await readFile((await (await download).path())!, 'utf8'));
  expect(evidence.source.csv).toBe(csv);
  expect(evidence.source.unit).toBe('us_survey_ft');
  expect(evidence.preview).toEqual(preview);
  await page.getByLabel('CSVの距離・高さの単位').selectOption('ft');
  await expect(page.getByRole('button', { name:'内容を確認して全測点を置換・施工案をクリア' })).toHaveCount(0);
  await page.getByRole('button', { name:'CSVを検証・プレビュー',exact:true }).click();
  await expect(page.getByRole('alert').filter({ hasText:'CSVを反映できません' })).toBeVisible();
  expect(await (await request.get(`/api/projects/${project.id}`)).json()).toEqual(project);
  await page.getByLabel('CSVの距離・高さの単位').selectOption('us_survey_ft');
  await page.getByRole('button', { name:'CSVを検証・プレビュー',exact:true }).click();
  await page.getByRole('button', { name:'内容を確認して全測点を置換・施工案をクリア' }).click();
  await expect(page.getByLabel('断面形式',{exact:true})).toHaveValue('survey');
  await page.getByRole('button', { name:'プロジェクトを保存',exact:true }).click();
  const saved = await (await request.get(`/api/projects/${project.id}`)).json();
  expect(saved.river.stations[1].chainage).toBeCloseTo(1200,10);
  expect(saved.river.discharge).toBe(project.river.discharge);
  expect(saved.river.boundary).toEqual(project.river.boundary);
  expect(saved.reference.import.unit).toBe('us_survey_ft');
  expect(saved.reference.import.sha256).toBe(createHash('sha256').update(csv).digest('hex'));
  const calculation = page.waitForResponse(r => r.url().endsWith('/api/runs') && r.request().method()==='POST');
  await page.getByRole('button', { name:'計算を実行',exact:true }).click();
  const run = await (await calculation).json();
  expect(run.analysis.project.reference.import.unit).toBe('us_survey_ft');
  expect(run.analysis.run.profile.rows[1].chainage).toBeCloseTo(1200,10);
  await expect(page.getByText('数値計算と施工比較が完了しました')).toBeVisible();
  await page.reload();
  await page.getByLabel('保存済みプロジェクト').selectOption(project.id);
  expect(await (await request.get(`/api/runs/${run.id}`)).json()).toEqual(run);
});
